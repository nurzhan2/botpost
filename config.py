# Явные признаки рекламы/вакансий — такие сообщения выкидываем всегда.
#
# Это РЕГУЛЯРКИ с границами слов (\b), а не подстроки. Прежний список ловил
# обычные новости: "на работу" убивал «помогли устроиться на работу»,
# "заработок" — «заработок отца влияет на уклад семьи», "крипт" — «о рисках
# вложений в крипте». Жадные шаблоны сужены до устойчивых оборотов вербовки.

# «Требуется» и «ищем людей» сами по себе встречаются в обычных новостях
# («требуется молитва о болящих», «ищем людей помочь в трапезной»), поэтому
# они срабатывают только рядом с денежно-кадровым контекстом.
